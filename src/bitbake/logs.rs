/// The shell exit trap's report: `WARNING: <run file>:<line> exit <n> from '<cmd>'` and the
/// backtrace after it (bash only; dash prints `WARNING: exit code <n> from a shell
/// command.` with no line).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct ShellTrace {
    /// The run file as printed (`.../temp/run.do_<task>.<pid>`).
    pub run_file: PathBuf,
    pub line: u32,
    pub exit_code: i32,
    pub command: String,
    /// Innermost first, as printed (`#1` is the function that ran the failing command).
    pub frames: Vec<Frame>,
    /// True when the frames came from `Backtrace (metadata-relative locations):`, i.e.
    /// their files are metadata files, not the run file.
    pub metadata_relative: bool,
}

/// The last shell exit trap report in `text`, if any.
pub fn shell_trace(text: &str) -> Option<ShellTrace> {
    let p = PATTERNS.as_ref()?;
    let lines: Vec<String> = text.lines().map(|l| clean_line(p, l).0).collect();
    let mut found = None;
    for (i, line) in lines.iter().enumerate() {
        if let Some(c) = p.trap_bash.captures(line) {
            let mut frames = Vec::new();
            let mut j = i + 1;
            if lines
                .get(j)
                .is_some_and(|l| l.starts_with("WARNING: Backtrace"))
            {
                j += 1;
                while let Some(fc) = lines.get(j).and_then(|l| p.trap_frame.captures(l)) {
                    frames.push(Frame {
                        file: fc[3].to_string(),
                        line: fc[4].parse().unwrap_or(0),
                        function: fc[2].to_string(),
                    });
                    j += 1;
                }
            }
            found = Some(ShellTrace {
                run_file: PathBuf::from(&c[1]),
                line: c[2].parse().unwrap_or(0),
                exit_code: c[3].parse().unwrap_or(1),
                command: c[4].to_string(),
                frames,
                metadata_relative: false,
            });
        } else if line.starts_with("Backtrace (metadata-relative locations):")
            && let Some(t) = found.as_mut()
        {
            let frames: Vec<Frame> = lines[i + 1..]
                .iter()
                .map_while(|l| p.trap_frame.captures(l))
                .map(|fc| Frame {
                    file: fc[3].to_string(),
                    line: fc[4].parse().unwrap_or(0),
                    function: fc[2].to_string(),
                })
                .collect();
            if !frames.is_empty() {
                t.frames = frames;
                t.metadata_relative = true;
            }
        }
    }
    found
}

/// Shell helpers that are never the interesting frame: logging, `die` and the
/// `oe_runmake` wrappers from OE-core's base.bbclass / logging.bbclass, and `main`.
const HELPER_FUNCTIONS: &[&str] = &[
    "main",
    "bbfatal",
    "bbfatal_log",
    "bberror",
    "bbwarn",
    "bbnote",
    "bbplain",
    "bbdebug",
    "die",
    "oe_runmake",
    "oe_runmake_call",
];

/// The function in `run.do_<task>` that failed.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct FailingFunction {
    /// The innermost frame that is not a helper (see [`HELPER_FUNCTIONS`]).
    pub function: String,
    /// Every frame except `main`, innermost first.
    pub chain: Vec<String>,
    /// Line in the run file.
    pub run_line: u32,
    /// Where that line is in the metadata: from the `# line: N, file: F` comment BitBake
    /// writes above each function in the run file (`bb.data.emit_var`), using the same
    /// arithmetic as `bb.build.exec_func_shell`. `None` without the run file.
    pub source: Option<(PathBuf, u32)>,
}

/// The failing function, from the trap report and (optionally) the run file's text.
pub fn failing_function(trace: &ShellTrace, run_script: Option<&str>) -> Option<FailingFunction> {
    let chain: Vec<String> = trace
        .frames
        .iter()
        .filter(|f| f.function != "main")
        .map(|f| f.function.clone())
        .collect();
    let frame = trace
        .frames
        .iter()
        .find(|f| !HELPER_FUNCTIONS.contains(&f.function.as_str()))
        .or_else(|| trace.frames.first())?;
    let source = if trace.metadata_relative {
        Some((PathBuf::from(&frame.file), frame.line))
    } else {
        run_script.and_then(|s| metadata_line(s, frame.line))
    };
    Some(FailingFunction {
        function: frame.function.clone(),
        chain,
        run_line: frame.line,
        source,
    })
}

/// Maps a 1-based line of a run file to `(metadata file, line)`: searches backwards for
/// the `# line: N, file: F` comment and applies `N + (line - comment_index - 2)` where
/// `comment_index` is 0-based (bb.build.exec_func_shell).
pub fn metadata_line(run_script: &str, line: u32) -> Option<(PathBuf, u32)> {
    let lines: Vec<&str> = run_script.lines().collect();
    let start = usize::try_from(line).ok()?.checked_sub(1)?;
    if start >= lines.len() {
        return None;
    }
    for i in (0..=start).rev() {
        if let Some(rest) = lines[i].strip_prefix("# line: ") {
            let (n, file) = rest.split_once(", file: ")?;
            let n: i64 = n.trim().parse().ok()?;
            let rel = i64::from(line) - i64::try_from(i).ok()? - 2;
            let meta = u32::try_from(n + rel).ok()?;
            return Some((PathBuf::from(file.trim()), meta));
        }
    }
    None
}

