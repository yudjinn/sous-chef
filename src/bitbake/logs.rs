/// Inputs to [`digest`]. Only `text` is required.
#[derive(Debug, Clone, Copy, Default)]
pub struct DigestInput<'a> {
    /// The log (or console output) text.
    pub text: &'a str,
    /// Where the log was read from; gives recipe, version and task.
    pub log_path: Option<&'a Path>,
    /// Text of the `run.do_<task>` file the trap report names, if it could be read.
    pub run_script: Option<&'a str>,
    /// Maps absolute paths to pointers.
    pub ws: Option<&'a Workspace>,
    /// The handle the full log is stored under.
    pub handle: Option<&'a Handle>,
    /// Pointer to the task definition in the layers (from the index).
    pub definition: Option<&'a Loc>,
}

/// The first error, ready to print.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct DigestError {
    pub kind: FailureKind,
    pub line: u32,
    pub span: LineSpan,
    pub message: String,
    pub detail: Option<String>,
    /// A few lines of context, each a snippet.
    pub context: Vec<String>,
}

/// A log digest. [`Digest::render`] prints it in about 600 bytes.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Digest {
    pub meta: LogMeta,
    pub log: Option<String>,
    pub first: Option<DigestError>,
    /// For a fetch failure: the downloader's first error line (`wget: unable to resolve host
    /// address ...`, `... ERROR 404: Not Found.`), which states the cause, with its line.
    pub cause: Option<(u32, String)>,
    /// How many other distinct downloader error lines the log has (mirrors tried after the
    /// upstream URL).
    pub more_causes: usize,
    /// Other distinct errors that are not consequences of the first.
    pub more: usize,
    pub function: Option<FailingFunction>,
    /// The failing function's location as a pointer or `path:line`.
    pub function_at: Option<String>,
    pub definition: Option<String>,
    pub handle: Option<Handle>,
    /// Extra lines (e.g. how the log was found), printed before the hint.
    pub notes: Vec<String>,
}

/// Builds the digest of a log.
pub fn digest(input: &DigestInput<'_>) -> Digest {
    let text_meta = meta_from_text(input.text);
    let meta = match input.log_path {
        Some(p) => meta_from_path_in(p, input.ws).or(text_meta),
        None => text_meta,
    };
    let failures = detect(input.text);
    let lines: Vec<&str> = input.text.lines().collect();
    let first = first_error(&failures).map(|f| DigestError {
        kind: f.kind,
        line: f.line,
        span: f.span,
        message: f.message.clone(),
        detail: f.detail.clone(),
        context: context_lines(f, &lines, input.ws),
    });
    let more = match first_error(&failures) {
        Some(f) => failures
            .iter()
            .filter(|o| o.rank <= Rank::Generic && o.line != f.line)
            .count(),
        None => 0,
    };
    let function = shell_trace(input.text).and_then(|t| failing_function(&t, input.run_script));
    let function_at = function
        .as_ref()
        .and_then(|f| f.source.as_ref())
        .map(|(file, line)| pointer_or_path(input.ws, file, *line));
    let mut causes = if first.as_ref().is_some_and(|e| e.kind == FailureKind::Fetch) {
        download_causes(input.text)
    } else {
        Vec::new()
    };
    let more_causes = causes.len().saturating_sub(1);
    let cause = (!causes.is_empty()).then(|| causes.swap_remove(0));
    Digest {
        meta,
        log: input.log_path.map(|p| display_path(input.ws, p)),
        first,
        cause,
        more_causes,
        more,
        function,
        function_at,
        definition: input.definition.map(|l| l.to_string()),
        handle: input.handle.cloned(),
        notes: Vec::new(),
    }
}

/// `layer:path:line` when `file` is in the workspace, else `file:line`.
fn pointer_or_path(ws: Option<&Workspace>, file: &Path, line: u32) -> String {
    ws.and_then(|w| w.loc_for(file, LineSpan::line(line)))
        .map(|l| l.to_string())
        .unwrap_or_else(|| format!("{}:{line}", file.display()))
}

/// A log path relative to the build directory when inside it.
fn display_path(ws: Option<&Workspace>, p: &Path) -> String {
    ws.and_then(|w| w.build_dir.as_ref())
        .and_then(|b| p.strip_prefix(b).ok())
        .map(|r| format!("{BUILD_LAYER}:{}", r.display()))
        .unwrap_or_else(|| p.display().to_string())
}

/// Context for the first error, by kind.
fn context_lines(f: &Failure, lines: &[&str], ws: Option<&Workspace>) -> Vec<String> {
    let Some(p) = PATTERNS.as_ref() else {
        return Vec::new();
    };
    let get = |n: u32| -> Option<String> {
        let i = usize::try_from(n).ok()?.checked_sub(1)?;
        let l = clean_line(p, lines.get(i)?).0;
        if l.starts_with("DEBUG:") || l.starts_with("NOTE:") {
            return None;
        }
        let s = render::snippet(&l);
        (!s.is_empty()).then_some(s)
    };
    let range = f.span.start..=f.span.end;
    let mut out: Vec<String> = match f.kind {
        FailureKind::Python => python_context(&f.frames, ws),
        FailureKind::Patch => range
            .filter(|&n| n != f.line)
            .filter_map(get)
            .filter(|l| {
                l.contains("FAILED") || l.contains("does not apply") || l.contains("rejects")
            })
            .collect(),
        FailureKind::Configure => range
            .filter(|&n| n != f.line)
            .filter_map(get)
            .filter(|l| !l.starts_with("configure: error: in `"))
            .collect(),
        // The fetch command line before `FetchError` is the whole command with its
        // environment; the cause row says what matters.
        FailureKind::Fetch => range
            .filter(|&n| n != f.line)
            .filter_map(get)
            .filter(|l| !l.starts_with("ERROR: Fetcher failure: Fetch command "))
            .collect(),
        _ => range.filter(|&n| n != f.line).filter_map(get).collect(),
    };
    out.truncate(DIGEST_CONTEXT_LINES);
    out
}

/// The exception's location: the last frame in a layer file, else the last frame with an
/// absolute path.
fn python_context(frames: &[Frame], ws: Option<&Workspace>) -> Vec<String> {
    let in_layer = |f: &&Frame| {
        ws.and_then(|w| w.loc_for(Path::new(&f.file), LineSpan::line(f.line)))
            .is_some_and(|l| l.layer != BUILD_LAYER)
    };
    let frame = frames
        .iter()
        .rev()
        .find(in_layer)
        .or_else(|| frames.iter().rev().find(|f| f.file.starts_with('/')));
    match frame {
        Some(f) => vec![format!(
            "in {} at {}",
            f.function,
            pointer_or_path(ws, Path::new(&f.file), f.line)
        )],
        None => Vec::new(),
    }
}

impl Digest {
    /// The digest as a two-column `field value` table, then the hint line.
    pub fn table(&self, context_rows: usize, with_log: bool) -> Table {
        let mut t = Table::new(&["field", "value"]);
        let m = &self.meta;
        if let Some(r) = m.recipe.as_ref().or(m.pf.as_ref()) {
            t.row(&["recipe", r]);
        }
        if let Some(v) = &m.version {
            t.row(&["version", v]);
        }
        if let Some(task) = &m.task {
            t.row(&["task", task]);
        }
        if let Some(c) = m.exit_code {
            t.row(&["exit", &c.to_string()]);
        }
        match &self.first {
            Some(e) => {
                let label = format!("error ({}, line {})", e.kind.as_str(), e.line);
                t.row(&[&label, &render::snippet(&e.message)]);
                if let Some(d) = &e.detail {
                    let field = match e.kind {
                        FailureKind::Fetch => "url",
                        FailureKind::Patch => "patch",
                        FailureKind::Qa => "qa class",
                        FailureKind::Python => "exception",
                        _ => "detail",
                    };
                    // Python's exception type and the patch name are in the message.
                    if !matches!(e.kind, FailureKind::Python | FailureKind::Patch) {
                        t.row(&[field, &render::snippet(d)]);
                    }
                }
                if let Some((line, c)) = &self.cause {
                    let mut v = render::snippet(c);
                    if self.more_causes > 0 {
                        v.push_str(&format!(" (+{} more download errors)", self.more_causes));
                    }
                    t.row(&[&format!("cause (line {line})"), &v]);
                }
                for c in e.context.iter().take(context_rows) {
                    t.row(&["context", c]);
                }
                if self.more > 0 {
                    t.row(&["more", &format!("+{} more errors", self.more)]);
                }
            }
            None => t.row(&["error", "no error lines recognised; slice the log"]),
        }
        if let Some(f) = &self.function {
            let mut v = match &self.function_at {
                Some(at) => format!("{} at {at}", f.function),
                None => format!("{} (run file line {})", f.function, f.run_line),
            };
            // Callers, without the logging / oe_runmake helpers and `main`.
            let callers: Vec<&str> = f
                .chain
                .iter()
                .skip_while(|c| **c != f.function)
                .skip(1)
                .filter(|c| !HELPER_FUNCTIONS.contains(&c.as_str()))
                .map(String::as_str)
                .collect();
            if !callers.is_empty() {
                v.push_str(&format!("; called from {}", callers.join(" < ")));
            }
            t.row(&["function", &render::snippet(&v)]);
        }
        if let Some(d) = &self.definition {
            t.row(&["definition", d]);
        }
        if with_log && let Some(l) = &self.log {
            t.row(&["log", &render::snippet(l)]);
        }
        if let Some(h) = &self.handle {
            t.row(&["handle", &h.0]);
        }
        for n in &self.notes {
            t.note(n);
        }
        if let Some(h) = self.hint() {
            t.note(&h);
        }
        t
    }

    /// `slice handle=h:... failures=true | grep=RE | lines=A-B`, with the first error's
    /// block as the line range.
    pub fn hint(&self) -> Option<String> {
        let h = self.handle.as_ref()?;
        let lines = self
            .first
            .as_ref()
            .map(|e| e.span.to_string())
            .unwrap_or_else(|| "A-B".into());
        Some(format!(
            "slice handle={h} failures=true | grep=RE | lines={lines}"
        ))
    }

    /// Renders through `render.rs`, dropping context rows and then the log path until the
    /// text form fits in [`DIGEST_MAX_BYTES`].
    pub fn render(&self, format: Format, budget_tokens: usize) -> String {
        let mut rows = DIGEST_CONTEXT_LINES;
        let mut with_log = true;
        loop {
            let t = self.table(rows, with_log);
            let text = t.render(budget_tokens);
            let fits = text.len() <= DIGEST_MAX_BYTES;
            if fits || (rows == 0 && !with_log) {
                return t.render_as(format, budget_tokens);
            }
            if rows > 0 {
                rows -= 1;
            } else {
                with_log = false;
            }
        }
    }
}

