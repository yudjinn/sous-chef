/// What a log says about the failing task. Every field is optional: each source fills
/// what it knows.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize)]
pub struct LogMeta {
    /// `PN`.
    pub recipe: Option<String>,
    /// `PV`: from the version directory under `WORKDIR`, or from the recipe file name.
    /// [`meta_from_path`] alone cannot tell the layouts apart and gives the directory name
    /// as it is (`1.0-r0` on a release with `Feature::PrInWorkdir`);
    /// [`meta_from_path_in`] uses the workspace release and gives `PV`.
    pub version: Option<String>,
    /// `PF` from a console prefix, when the recipe name is not known otherwise.
    pub pf: Option<String>,
    /// `do_<task>`.
    pub task: Option<String>,
    pub exit_code: Option<i32>,
    /// The recipe file, from `ERROR: Task (<file>:<task>) failed`.
    pub recipe_file: Option<PathBuf>,
}

impl LogMeta {
    /// Fills fields that are `None` from `other`.
    pub fn or(mut self, other: LogMeta) -> LogMeta {
        self.recipe = self.recipe.or(other.recipe);
        self.version = self.version.or(other.version);
        self.pf = self.pf.or(other.pf);
        self.task = self.task.or(other.task);
        self.exit_code = self.exit_code.or(other.exit_code);
        self.recipe_file = self.recipe_file.or(other.recipe_file);
        self
    }
}

/// From a task log path `.../work/<arch>/<pn>/<version>/temp/log.do_<task>[.<pid>]`
/// (`WORKDIR = ${BASE_WORKDIR}/${MULTIMACH_TARGET_SYS}/${PN}/${PV}` in OE-core from
/// nanbield; `.../${PN}/${EXTENDPE}${PV}-${PR}` up to mickledore, `Feature::PrInWorkdir`).
/// The version directory is returned as it is; [`meta_from_path_in`] splits it by release.
/// The task comes from the file name even when the directory layout differs.
pub fn meta_from_path(path: &Path) -> LogMeta {
    let mut meta = LogMeta::default();
    let name = path
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default();
    if let Some(rest) = name.strip_prefix("log.do_") {
        let task = match rest.rsplit_once('.') {
            Some((t, pid)) if !pid.is_empty() && pid.bytes().all(|b| b.is_ascii_digit()) => t,
            _ => rest,
        };
        meta.task = Some(format!("do_{task}"));
    }
    let parts: Vec<String> = path
        .components()
        .map(|c| c.as_os_str().to_string_lossy().into_owned())
        .collect();
    let n = parts.len();
    if n >= 6 && parts[n - 2] == "temp" && parts[n - 6] == "work" {
        meta.recipe = Some(parts[n - 4].clone());
        meta.version = Some(parts[n - 3].clone());
    }
    meta
}

/// [`meta_from_path`], with the version directory read for the workspace's release: on a
/// release with `Feature::PrInWorkdir` it is `${EXTENDPE}${PV}-${PR}` (`EXTENDPE` is
/// `${PE}_` when `PE` is set), so `PV` is what is left after removing the last `-<PR>`
/// and a leading `<digits>_`. On later releases, and without a workspace, it is `PV`.
pub fn meta_from_path_in(path: &Path, ws: Option<&Workspace>) -> LogMeta {
    let mut meta = meta_from_path(path);
    let pr_in_workdir =
        ws.is_some_and(|ws| ws.release.release.has(crate::release::Feature::PrInWorkdir));
    if pr_in_workdir && let Some(dir) = &meta.version {
        meta.version = Some(pv_from_pr_workdir(dir).to_string());
    }
    meta
}

/// `PV` from `${EXTENDPE}${PV}-${PR}`. A name without `-` is returned whole.
fn pv_from_pr_workdir(dir: &str) -> &str {
    let without_pr = dir.rsplit_once('-').map_or(dir, |(pv, _)| pv);
    match without_pr.split_once('_') {
        Some((pe, pv)) if !pe.is_empty() && pe.bytes().all(|b| b.is_ascii_digit()) => pv,
        _ => without_pr,
    }
}

/// From log or console text: the knotty prefix (`PF`, task), `ERROR: Task (<file>:<task>)
/// failed with exit code 'N'`, `Execution of '...' failed with exit code N`, the shell exit
/// trap, and `DEBUG: Executing ... function do_<task>`.
pub fn meta_from_text(text: &str) -> LogMeta {
    let Some(p) = PATTERNS.as_ref() else {
        return LogMeta::default();
    };
    let mut meta = LogMeta::default();
    let mut executing = None;
    for raw in text.lines() {
        let (line, prefix) = clean_line(p, raw);
        if let Some((pf, task)) = prefix
            && line.starts_with("ERROR:")
            && meta.pf.is_none()
        {
            meta.pf = Some(pf);
            meta.task.get_or_insert(task);
        }
        if let Some(c) = p.task_failed.captures(&line) {
            let file = PathBuf::from(&c[1]);
            if meta.recipe_file.is_none() {
                let (pn, pv) = pn_pv_from_file(&file);
                meta.recipe = meta.recipe.or(pn);
                meta.version = meta.version.or(pv);
                meta.recipe_file = Some(file);
                meta.task = Some(c[2].to_string());
                meta.exit_code = c[3].parse().ok().or(meta.exit_code);
            }
        } else if let Some(c) = p.exec_failed.captures(&line) {
            meta.exit_code = meta.exit_code.or(c[2].parse().ok());
        } else if let Some(c) = p.trap_bash.captures(&line) {
            meta.exit_code = meta.exit_code.or(c[3].parse().ok());
        } else if let Some(c) = p.trap_sh.captures(&line) {
            meta.exit_code = meta.exit_code.or(c[1].parse().ok());
        } else if executing.is_none()
            && let Some(c) = p.executing.captures(&line)
        {
            executing = Some(c[1].to_string());
        }
    }
    meta.task = meta.task.or(executing);
    meta
}

/// `PN` and `PV` from a recipe file name `<pn>_<pv>.bb` (`bb.parse.vars_from_file` splits
/// the base name on `_`).
fn pn_pv_from_file(file: &Path) -> (Option<String>, Option<String>) {
    let stem = match file.extension().and_then(|e| e.to_str()) {
        Some("bb") | Some("bbappend") => file.file_stem().and_then(|s| s.to_str()),
        _ => None,
    };
    let Some(stem) = stem else {
        return (None, None);
    };
    let mut parts = stem.split('_');
    let pn = parts.next().filter(|s| !s.is_empty()).map(str::to_string);
    let pv = parts.next().filter(|s| !s.is_empty()).map(str::to_string);
    (pn, pv)
}

