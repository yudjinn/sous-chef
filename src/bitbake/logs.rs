/// What kind of failure a block is.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum FailureKind {
    /// Compiler diagnostic `file:line:col: error: ...`.
    Compile,
    /// Linker failure (`undefined reference`, `cannot find -l...`, `collect2`).
    Link,
    /// `configure: error:`, `CMake Error at`, meson `ERROR:`.
    Configure,
    /// `make: *** ...`.
    Make,
    /// Fetcher failure (`do_fetch`).
    Fetch,
    /// Patch that does not apply (`do_patch`).
    Patch,
    /// `ERROR: QA Issue: ... [class]`.
    Qa,
    /// Python task traceback.
    Python,
    /// Shell command failure (`command not found`, the exit trap's warnings).
    Shell,
    /// Any other `ERROR:` line.
    Error,
}

impl FailureKind {
    pub fn as_str(self) -> &'static str {
        match self {
            FailureKind::Compile => "compile",
            FailureKind::Link => "link",
            FailureKind::Configure => "configure",
            FailureKind::Make => "make",
            FailureKind::Fetch => "fetch",
            FailureKind::Patch => "patch",
            FailureKind::Qa => "qa",
            FailureKind::Python => "python",
            FailureKind::Shell => "shell",
            FailureKind::Error => "error",
        }
    }
}

/// How much a failure says about the cause. Ordered: [`first_error`] prefers `Specific`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Rank {
    /// A recognised message that names the cause (compiler error, fetch URL, patch, ...).
    Specific,
    /// An unrecognised `ERROR:` line.
    Generic,
    /// A consequence of an earlier error: `make: *** ... Error 2`, `oe_runmake failed`,
    /// `Task (...) failed with exit code`, the shell exit trap, `Fatal QA errors`.
    Consequence,
}

/// One frame of a python traceback or of the shell exit trap's backtrace.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Frame {
    /// As printed: an absolute path, a generated script, or `exec_func_python() autogenerated`.
    pub file: String,
    pub line: u32,
    pub function: String,
}

/// A failure block found in a log.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Failure {
    pub kind: FailureKind,
    pub rank: Rank,
    /// The line that carries the error, 1-based in the input text.
    pub line: u32,
    /// The block: the error line plus its context, 1-based and inclusive, within the input.
    /// `slice failures=true` returns these lines.
    pub span: LineSpan,
    /// One line, prefixes (`| `, `ERROR: <PF> <task>: `) removed.
    pub message: String,
    /// Fetch: the URL. Patch: the patch file name. QA: the QA class. Shell trap:
    /// `run file:line`. Python: the exception type.
    pub detail: Option<String>,
    /// Python tracebacks only, outermost first.
    pub frames: Vec<Frame>,
}

/// Finds the failure blocks in `text` (a task log or bitbake console output), in log
/// order, de-duplicated: a failure whose kind and message equal an earlier one's is dropped
/// (console output repeats task errors under `Log data follows:`).
///
/// Never fails; unknown text yields no failures. Lines are numbered from 1 as in
/// `text.lines()`.
pub fn detect(text: &str) -> Vec<Failure> {
    let Some(p) = PATTERNS.as_ref() else {
        return Vec::new();
    };
    let lines: Vec<String> = text.lines().map(|l| clean_line(p, l).0).collect();
    let mut out: Vec<Failure> = Vec::new();
    let mut seen: HashSet<(FailureKind, String)> = HashSet::new();
    let mut i = 0;
    while i < lines.len() {
        let (found, consumed) = match_line(p, &lines, i);
        if let Some(f) = found
            && seen.insert((f.kind, f.message.clone()))
        {
            out.push(f);
        }
        i = consumed.max(i + 1);
    }
    out
}

/// The failure to show first: the earliest of the best rank present.
pub fn first_error(failures: &[Failure]) -> Option<&Failure> {
    failures.iter().min_by_key(|f| (f.rank, f.line))
}

/// Compiled patterns. `None` only if a pattern fails to compile, which a unit test rules
/// out; detection then finds nothing rather than panicking.
static PATTERNS: LazyLock<Option<Patterns>> = LazyLock::new(|| Patterns::new().ok());

struct Patterns {
    pipe: Regex,
    knotty: Regex,
    compile: Regex,
    meson: Regex,
    cmake: Regex,
    link: Regex,
    make: Regex,
    fetch_url: Regex,
    fetch_repr: Regex,
    fetch_cmd: Regex,
    download_cause: Regex,
    patch: Regex,
    qa: Regex,
    py_bb_start: Regex,
    py_bb_frame: Regex,
    py_tb_frame: Regex,
    trap_bash: Regex,
    trap_sh: Regex,
    trap_frame: Regex,
    task_failed: Regex,
    exec_failed: Regex,
    executing: Regex,
    shell_err: Regex,
}

impl Patterns {
    fn new() -> std::result::Result<Patterns, regex::Error> {
        Ok(Patterns {
            // knotty: ' | ' when BBINCLUDELOGS_LINES is set, '| ' otherwise.
            pipe: Regex::new(r"^ ?\|(?: |$)")?,
            knotty: Regex::new(r"^(ERROR|WARNING|NOTE): (\S+) (do_[A-Za-z0-9_+.-]+): (.*)$")?,
            compile: Regex::new(r"^(\S.*?):(\d+):(?:(\d+):)? (?:fatal error|error): (.*)$")?,
            meson: Regex::new(r"^(\S*meson\.build):(\d+):(\d+): ERROR: (.*)$")?,
            cmake: Regex::new(r"^CMake Error at (\S+?):(\d+)")?,
            link: Regex::new(
                r"undefined reference to |: cannot find -l\S+|^collect2: error: ld returned",
            )?,
            make: Regex::new(r"^g?make(?:\[\d+\])?: \*\*\* (.*)$")?,
            fetch_url: Regex::new(r"Fetcher failure for URL: '([^']*)'\. (.*)$")?,
            fetch_repr: Regex::new(
                r"Bitbake Fetcher Error: (\w+)\('((?:[^'\\]|\\.)*)', '([^']*)'\)",
            )?,
            // `FetchError` from `runfetchcmd` (`fetch2/__init__.py`), as `base_do_fetch`
            // logs it: the full command, its environment exports included, then the code.
            fetch_cmd: Regex::new(
                r"^ERROR: Fetcher failure: Fetch command (.*) failed with exit code (\d+)",
            )?,
            // The downloader's own statement of the cause, logged as plain output after the
            // `DEBUG: Running ...` (or `failed ..., output:`) line: wget's `wget: ...` and
            // `<date> <time> ERROR <code>: <reason>.`, curl's `curl: (<n>) ...`, git's
            // `fatal: ...`.
            download_cause: Regex::new(
                r"^(?:wget: .+|\d{4}-\d\d-\d\d \d\d:\d\d:\d\d ERROR \d+: .+|curl: \(\d+\) .+|fatal: .+)$",
            )?,
            patch: Regex::new(r"^ERROR: (?:Applying|Importing) patch '([^']+)'")?,
            qa: Regex::new(r"^ERROR: QA Issue: (.*?)(?: \[([A-Za-z0-9_-]+)\])?$")?,
            py_bb_start: Regex::new(r"^ERROR: Error executing a python function in (.*):$")?,
            py_bb_frame: Regex::new(r"^File: '(.*)', lineno: (\d+), function: (.*)$")?,
            py_tb_frame: Regex::new(r#"^\s+File "(.*)", line (\d+), in (.*)$"#)?,
            trap_bash: Regex::new(r"^WARNING: (\S+):(\d+) exit (\d+) from '(.*)'$")?,
            trap_sh: Regex::new(r"^WARNING: exit code (\d+) from a shell command\.")?,
            trap_frame: Regex::new(r"^\s*#(\d+): (\S+), (.+?), line (\d+)$")?,
            task_failed: Regex::new(
                r"^ERROR: Task \((.+):(do_[^)\s]+)\) failed with exit code '(\d+)'",
            )?,
            exec_failed: Regex::new(r"^ERROR: Execution of '([^']*)' failed with exit code (\d+)")?,
            executing: Regex::new(r"^DEBUG: Executing (?:shell|python) function (do_\S+)$")?,
            shell_err: Regex::new(
                r"^(?:/bin/sh: |\S+: line \d+: )?(\S+): (?:command not found|cannot stat .*|cannot access .*|cannot create .*|.*: No such file or directory)$",
            )?,
        })
    }
}

/// Removes the console prefixes: `| ` (log data) and `ERROR: <PF> <task>: ` (knotty puts
/// the recipe and task before every message from a task). Returns the line and the
/// `(PF, task)` from the prefix, if any.
fn clean_line(p: &Patterns, raw: &str) -> (String, Option<(String, String)>) {
    let line = raw.trim_end_matches('\r');
    let line = match p.pipe.find(line) {
        Some(m) => &line[m.end()..],
        None => line,
    };
    if let Some(c) = p.knotty.captures(line) {
        let level = &c[1];
        let rest = &c[4];
        return (
            format!("{level}: {rest}"),
            Some((c[2].to_string(), c[3].to_string())),
        );
    }
    (line.to_string(), None)
}

fn lno(i: usize) -> u32 {
    u32::try_from(i + 1).unwrap_or(u32::MAX)
}

fn span(lines: &[String], from: usize, to: usize) -> LineSpan {
    let last = lines.len().saturating_sub(1);
    LineSpan::new(lno(from.min(last)), lno(to.min(last).max(from.min(last))))
}

fn failure(
    kind: FailureKind,
    rank: Rank,
    i: usize,
    sp: LineSpan,
    message: &str,
    detail: Option<String>,
) -> Failure {
    Failure {
        kind,
        rank,
        line: lno(i),
        span: sp,
        message: message.trim().to_string(),
        detail,
        frames: Vec::new(),
    }
}

/// Messages that only restate that an earlier step failed.
fn is_consequence(msg: &str) -> bool {
    const PREFIXES: &[&str] = &[
        "Logfile of failure stored in",
        "Task (",
        "Execution of '",
        "Function failed:",
        "oe_runmake failed",
        "configure failed",
        "autoreconf execution failed",
        "Fatal QA errors were found",
        "Command Error:",
        "Summary:",
    ];
    PREFIXES.iter().any(|p| msg.starts_with(p))
}

/// The program a fetch command runs: the word after `/usr/bin/env ` (OE-core's
/// `FETCHCMD_wget = "/usr/bin/env wget ..."`), else the first word after the last `;` (the
/// `export ...;` prefixes `runfetchcmd` adds).
fn downloader(command: &str) -> String {
    let after_env = match command.split_once("/usr/bin/env ") {
        Some((_, rest)) => rest,
        None => command.rsplit(';').next().unwrap_or(command),
    };
    after_env
        .split_whitespace()
        .next()
        .map(|w| w.rsplit('/').next().unwrap_or(w).to_string())
        .unwrap_or_else(|| "the fetch command".to_string())
}

/// The downloader's own error lines in a log (wget, curl, git; see `download_cause`), in
/// order, without repeats: `(1-based line, text)`.
pub fn download_causes(text: &str) -> Vec<(u32, String)> {
    let Some(p) = PATTERNS.as_ref() else {
        return Vec::new();
    };
    let mut out: Vec<(u32, String)> = Vec::new();
    for (i, raw) in text.lines().enumerate() {
        let cleaned = clean_line(p, raw).0;
        let line = cleaned.trim();
        if p.download_cause.is_match(line) && !out.iter().any(|(_, l)| l == line) {
            out.push((lno(i), line.to_string()));
        }
    }
    out
}

/// Matches the line at `i`. Returns the failure, if any, and the index of the next line
/// to look at (blocks such as a python traceback are consumed whole).
fn match_line(p: &Patterns, lines: &[String], i: usize) -> (Option<Failure>, usize) {
    let line = lines[i].as_str();
    let next = i + 1;
    let before = |n: usize| i.saturating_sub(n);

    if line.starts_with("DEBUG:") || line.starts_with("NOTE:") {
        return (None, next);
    }

    // Python task traceback (bb.utils._print_exception).
    if p.py_bb_start.is_match(line) {
        return python_bb_block(p, lines, i);
    }
    if line.starts_with("Traceback (most recent call last):") {
        return python_tb_block(p, lines, i);
    }

    // Patch: the ERROR line, then quilt's output up to `stderr:`.
    if let Some(c) = p.patch.captures(line) {
        let name = Path::new(&c[1])
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_else(|| c[1].to_string());
        let end = (i + 1..lines.len().min(i + 20))
            .find(|&j| lines[j].starts_with("stderr:") || lines[j].starts_with("DEBUG:"))
            .unwrap_or_else(|| (i + 8).min(lines.len().saturating_sub(1)));
        // The target directory is long and always `${S}`-ish; the patch name is what matters.
        let msg = line.trim_start_matches("ERROR: ");
        let msg = msg.split(" on target directory '").next().unwrap_or(msg);
        let f = failure(
            FailureKind::Patch,
            Rank::Specific,
            i,
            span(lines, i, end),
            msg,
            Some(name),
        );
        return (Some(f), end + 1);
    }

    if let Some(c) = p.qa.captures(line) {
        let f = failure(
            FailureKind::Qa,
            Rank::Specific,
            i,
            span(lines, i, i),
            &format!("QA Issue: {}", &c[1]),
            c.get(2).map(|m| m.as_str().to_string()),
        );
        return (Some(f), next);
    }

    if let Some(c) = p.fetch_repr.captures(line) {
        let msg = c[2].replace("\\'", "'");
        let f = failure(
            FailureKind::Fetch,
            Rank::Specific,
            i,
            span(lines, before(1), i),
            &format!("{}: {msg}", &c[1]),
            Some(c[3].to_string()),
        );
        return (Some(f), next);
    }
    if let Some(c) = p.fetch_url.captures(line) {
        let f = failure(
            FailureKind::Fetch,
            Rank::Specific,
            i,
            span(lines, i, i + 2),
            &c[2],
            Some(c[1].to_string()),
        );
        return (Some(f), next);
    }

    if let Some(c) = p.fetch_cmd.captures(line) {
        // The command (with the environment it exported) is long and says nothing that the
        // URL and the downloader's own error line do not: keep the program and the code.
        let program = downloader(&c[1]);
        let f = failure(
            FailureKind::Fetch,
            Rank::Consequence,
            i,
            span(lines, i, i),
            &format!("Fetcher failure: {program} failed with exit code {}", &c[2]),
            Some(program),
        );
        return (Some(f), next);
    }

    if p.compile.is_match(line) {
        let from = if i > 0
            && (lines[i - 1].contains(": In function")
                || lines[i - 1].contains(": In member function")
                || lines[i - 1].starts_with("In file included from"))
        {
            i - 1
        } else {
            i
        };
        let f = failure(
            FailureKind::Compile,
            Rank::Specific,
            i,
            span(lines, from, i + 2),
            line,
            None,
        );
        return (Some(f), next);
    }
    if p.meson.is_match(line) || p.cmake.is_match(line) {
        let msg = if p.cmake.is_match(line) {
            let follow = lines.get(i + 1).map(|l| l.trim()).unwrap_or("");
            format!("{} {follow}", line.trim_end_matches(':'))
        } else {
            line.to_string()
        };
        let f = failure(
            FailureKind::Configure,
            Rank::Specific,
            i,
            span(lines, i, i + 2),
            &msg,
            None,
        );
        return (Some(f), next);
    }
    if let Some(rest) = line.strip_prefix("configure: error: ") {
        // AC_MSG_FAILURE prints `in `<dir>':` before the message itself.
        let rank = if rest.starts_with("in `") {
            Rank::Consequence
        } else {
            Rank::Specific
        };
        let f = failure(
            FailureKind::Configure,
            rank,
            i,
            span(lines, before(1), i + 1),
            line,
            None,
        );
        return (Some(f), next);
    }
    if p.link.is_match(line) {
        let rank = if line.starts_with("collect2:") {
            Rank::Consequence
        } else {
            Rank::Specific
        };
        let f = failure(
            FailureKind::Link,
            rank,
            i,
            span(lines, before(1), i),
            line,
            None,
        );
        return (Some(f), next);
    }
    if let Some(c) = p.make.captures(line) {
        let rank = if c[1].contains("No rule to make target") {
            Rank::Specific
        } else {
            Rank::Consequence
        };
        let f = failure(FailureKind::Make, rank, i, span(lines, i, i), line, None);
        return (Some(f), next);
    }

    // The shell exit trap (bb.build.shell_trap_code): bash names the run file and line.
    if let Some(c) = p.trap_bash.captures(line) {
        let mut end = i;
        if lines
            .get(i + 1)
            .is_some_and(|l| l.starts_with("WARNING: Backtrace"))
        {
            end = i + 1;
            while lines.get(end + 1).is_some_and(|l| p.trap_frame.is_match(l)) {
                end += 1;
            }
        }
        let f = failure(
            FailureKind::Shell,
            Rank::Consequence,
            i,
            span(lines, i, end),
            &format!("exit {} from '{}'", &c[3], &c[4]),
            Some(format!("{}:{}", &c[1], &c[2])),
        );
        return (Some(f), end + 1);
    }
    if let Some(c) = p.trap_sh.captures(line) {
        let f = failure(
            FailureKind::Shell,
            Rank::Consequence,
            i,
            span(lines, i, i),
            &format!("exit code {} from a shell command", &c[1]),
            None,
        );
        return (Some(f), next);
    }
    if p.shell_err.is_match(line) {
        let f = failure(
            FailureKind::Shell,
            Rank::Specific,
            i,
            span(lines, before(1), i + 1),
            line,
            None,
        );
        return (Some(f), next);
    }

    if let Some(msg) = line.strip_prefix("ERROR: ") {
        let rank = if is_consequence(msg) {
            Rank::Consequence
        } else {
            Rank::Generic
        };
        let f = failure(
            FailureKind::Error,
            rank,
            i,
            span(lines, i, i + 2),
            msg,
            None,
        );
        return (Some(f), next);
    }
    (None, next)
}

/// `ERROR: Error executing a python function in ...:` through `Exception: ...`.
fn python_bb_block(p: &Patterns, lines: &[String], i: usize) -> (Option<Failure>, usize) {
    let mut frames = Vec::new();
    let mut end = None;
    for (j, l) in lines.iter().enumerate().skip(i + 1).take(400) {
        if let Some(c) = p.py_bb_frame.captures(l) {
            frames.push(Frame {
                file: c[1].to_string(),
                line: c[2].parse().unwrap_or(0),
                function: c[3].to_string(),
            });
        } else if l.starts_with("Exception: ") {
            end = Some(j);
            break;
        } else if l.starts_with("DEBUG:") || (l.starts_with("ERROR:") && j > i + 1) {
            break;
        }
    }
    let (end, exception) = match end {
        Some(j) => (j, lines[j].trim_start_matches("Exception: ").trim()),
        None => (i, lines[i].trim_start_matches("ERROR: ").trim()),
    };
    let ty = exception
        .split_once(':')
        .map(|(t, _)| t.trim().to_string())
        .filter(|t| !t.contains(' '));
    let mut f = failure(
        FailureKind::Python,
        Rank::Specific,
        end,
        span(lines, i, end),
        exception,
        ty,
    );
    f.frames = frames;
    (Some(f), end + 1)
}

/// A standard python traceback: `Traceback (most recent call last):`, `  File "...", line
/// N, in f` frames, then the exception line.
fn python_tb_block(p: &Patterns, lines: &[String], i: usize) -> (Option<Failure>, usize) {
    let mut frames = Vec::new();
    let mut j = i + 1;
    while j < lines.len() {
        let l = &lines[j];
        if let Some(c) = p.py_tb_frame.captures(l) {
            frames.push(Frame {
                file: c[1].to_string(),
                line: c[2].parse().unwrap_or(0),
                function: c[3].to_string(),
            });
        } else if !l.starts_with(' ') && !l.starts_with('\t') && !l.trim().is_empty() {
            break;
        }
        j += 1;
    }
    let end = j.min(lines.len().saturating_sub(1));
    let exception = lines.get(j).map(|s| s.trim()).unwrap_or("Traceback");
    let exception = exception.trim_start_matches("ERROR: ");
    let ty = exception
        .split_once(':')
        .map(|(t, _)| t.trim().to_string())
        .filter(|t| !t.contains(' '));
    let mut f = failure(
        FailureKind::Python,
        Rank::Specific,
        end,
        span(lines, i, end),
        exception,
        ty,
    );
    f.frames = frames;
    (Some(f), end + 1)
}

