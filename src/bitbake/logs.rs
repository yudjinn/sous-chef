//! Build log location, failure detection and digests (T5.6).
//!
//! Three parts, usable separately:
//!
//! - **Detection** ([`detect`], [`first_error`]): pure text in, failure blocks out. Used by
//!   the digester, by `slice failures=true` and by the Bash hook (M7). Understands task
//!   logs (`log.do_<task>`), knotty console output (`ERROR: <PF> <task>: ...` prefixes and
//!   the `| ` "Log data follows" lines) and the formats BitBake and OE-core print; see
//!   "Build output" in `docs/bitbake-semantics.md` for the sources checked.
//! - **Location**: from console output ([`failure_logfiles`], [`failed_tasks`]), from
//!   `bitbake-getvar` ([`t_dir_from_bitbake`]) or by searching the build directory
//!   ([`find_task_logs`], [`newest_cooker_log`]).
//! - **Digest** ([`digest`], [`Digest::render`]): about 600 bytes naming the recipe,
//!   version, task, exit code, the first error with context, the failing shell function,
//!   a pointer to the task definition and the handle of the full log.
//!
//! Nothing here reads a file except the location helpers, which only list directories and
//! read file metadata; callers confine every path before reading its contents.

