/// Every `ERROR: Logfile of failure stored in: <path>` (knotty, `bb.ui.knotty`) and every
/// `    log: <path>` under `Summary: N task(s) failed:`, in order, without repeats.
pub fn failure_logfiles(output: &str) -> Vec<PathBuf> {
    let mut out: Vec<PathBuf> = Vec::new();
    let mut in_summary = false;
    for raw in output.lines() {
        let line = raw.trim_end_matches('\r');
        let path = if let Some(rest) = line
            .strip_prefix("ERROR: ")
            .and_then(|r| r.strip_prefix("Logfile of failure stored in: "))
        {
            Some(rest.trim())
        } else if line.starts_with("Summary: ") {
            in_summary = line.contains("failed:");
            None
        } else if in_summary {
            line.trim_start().strip_prefix("log: ").map(str::trim)
        } else {
            None
        };
        if let Some(p) = path.filter(|p| !p.is_empty()) {
            let p = PathBuf::from(p);
            if !out.contains(&p) {
                out.push(p);
            }
        }
    }
    out
}

/// A task failure from console output.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct FailedTask {
    pub recipe_file: PathBuf,
    /// `do_<task>`.
    pub task: String,
    pub exit_code: Option<i32>,
    /// The log, from the `Logfile of failure stored in:` line before it, if any.
    pub log: Option<PathBuf>,
}

/// Every `ERROR: Task (<recipe file>:<task>) failed with exit code 'N'` (`bb.runqueue`)
/// in `output`, with the log named most recently before it.
pub fn failed_tasks(output: &str) -> Vec<FailedTask> {
    let Some(p) = PATTERNS.as_ref() else {
        return Vec::new();
    };
    let mut out = Vec::new();
    let mut last_log: Option<PathBuf> = None;
    for raw in output.lines() {
        let line = raw.trim_end_matches('\r');
        if let Some(rest) = line.strip_prefix("ERROR: Logfile of failure stored in: ") {
            last_log = Some(PathBuf::from(rest.trim()));
        } else if let Some(c) = p.task_failed.captures(line) {
            out.push(FailedTask {
                recipe_file: PathBuf::from(&c[1]),
                task: c[2].to_string(),
                exit_code: c[3].parse().ok(),
                log: last_log.take(),
            });
        }
    }
    out
}

/// The exit status BitBake reported on the console for the task whose log is `log`: the
/// `ERROR: Task (<file>:<task>) failed with exit code 'N'` that follows `Logfile of failure
/// stored in: <log>` ([`failed_tasks`]). A task log does not carry it (`bb.runqueue`
/// prints it on the console only). Paths are compared by their last five components
/// (`<arch>/<pn>/<version>/temp/log.do_<task>.<pid>`), since the console may print them
/// through another route (`build/../`).
pub fn exit_from_console(output: &str, log: &Path) -> Option<i32> {
    let tail = |p: &Path| -> Vec<String> {
        let mut v: Vec<String> = p
            .components()
            .rev()
            .take(5)
            .map(|c| c.as_os_str().to_string_lossy().into_owned())
            .collect();
        v.reverse();
        v
    };
    let want = tail(log);
    failed_tasks(output)
        .into_iter()
        .find(|t| t.log.as_deref().is_some_and(|l| tail(l) == want))
        .and_then(|t| t.exit_code)
}

/// `compile` or `do_compile` -> `do_compile`. Task and recipe names may hold only
/// `[A-Za-z0-9_.+-]`, so they can be used as path components.
pub fn normalize_task(task: &str) -> Result<String> {
    let t = task.trim();
    check_name("task", t)?;
    Ok(if t.starts_with("do_") {
        t.to_string()
    } else {
        format!("do_{t}")
    })
}

/// Rejects names that could escape a directory (`/`, `..`) or are empty.
pub fn check_name(what: &str, name: &str) -> Result<()> {
    let ok = !name.is_empty()
        && !name.starts_with('.')
        && !name.starts_with('-')
        && name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b"_.+-".contains(&b));
    if ok {
        Ok(())
    } else {
        Err(Error::Invalid {
            msg: format!("invalid {what} name {name:?}; use letters, digits and _ . + - only"),
        })
    }
}

/// The `TMPDIR`s under the build directory: `tmp` (OE-core's default
/// `${TOPDIR}/tmp`) and `tmp-*` (older releases appended the C library, e.g.
/// `tmp-glibc`).
pub fn tmp_dirs(build_dir: &Path) -> Vec<PathBuf> {
    let mut out: Vec<PathBuf> = read_dir_sorted(build_dir)
        .into_iter()
        .filter(|p| {
            p.file_name()
                .and_then(|n| n.to_str())
                .is_some_and(|n| n == "tmp" || n.starts_with("tmp-"))
                && p.is_dir()
        })
        .collect();
    out.sort();
    out
}

/// Task logs under `<build>/tmp*/work/<arch>/<pn>/<version>/temp/`, newest first (by
/// modification time). `recipe` filters on the `<pn>` directory, `task` (`do_<task>`) on
/// the file name. Both `log.do_<task>` (the symlink BitBake keeps to the latest run) and
/// `log.do_<task>.<pid>` match; a symlink is dropped when its target is also listed.
pub fn find_task_logs(build_dir: &Path, recipe: Option<&str>, task: Option<&str>) -> Vec<PathBuf> {
    let mut temps = Vec::new();
    for tmp in tmp_dirs(build_dir) {
        for arch in read_dir_sorted(&tmp.join("work")) {
            let pns = match recipe {
                Some(r) => vec![arch.join(r)],
                None => read_dir_sorted(&arch),
            };
            for pn in pns {
                for ver in read_dir_sorted(&pn) {
                    temps.push(ver.join("temp"));
                }
            }
        }
    }
    let mut logs: Vec<PathBuf> = temps.iter().flat_map(|t| logs_in_t_dir(t, task)).collect();
    sort_newest_first(&mut logs);
    logs
}

/// Task logs in one `T` directory (`${WORKDIR}/temp`), newest first.
pub fn logs_in_t_dir(t_dir: &Path, task: Option<&str>) -> Vec<PathBuf> {
    let entries = read_dir_sorted(t_dir);
    let mut real: Vec<PathBuf> = Vec::new();
    let mut links: Vec<PathBuf> = Vec::new();
    for p in entries {
        let Some(name) = p.file_name().and_then(|n| n.to_str()) else {
            continue;
        };
        let Some(rest) = name.strip_prefix("log.do_") else {
            continue;
        };
        let (t, has_pid) = match rest.rsplit_once('.') {
            Some((t, pid)) if !pid.is_empty() && pid.bytes().all(|b| b.is_ascii_digit()) => {
                (t, true)
            }
            _ => (rest, false),
        };
        if let Some(want) = task
            && want.strip_prefix("do_").unwrap_or(want) != t
        {
            continue;
        }
        let is_link = fs::symlink_metadata(&p).is_ok_and(|m| m.file_type().is_symlink());
        if has_pid || !is_link {
            real.push(p);
        } else {
            links.push(p);
        }
    }
    for l in links {
        let target = fs::canonicalize(&l).ok();
        let dup = target.is_some_and(|t| {
            real.iter()
                .any(|r| fs::canonicalize(r).ok() == Some(t.clone()))
        });
        if !dup {
            real.push(l);
        }
    }
    sort_newest_first(&mut real);
    real
}

/// The newest console log under `<build>/tmp*/log/cooker/<machine>/` (OE-core's
/// `BB_CONSOLELOG = "${LOG_DIR}/cooker/${MACHINE}/${DATETIME}.log"`).
pub fn newest_cooker_log(build_dir: &Path) -> Option<PathBuf> {
    let mut logs: Vec<PathBuf> = tmp_dirs(build_dir)
        .iter()
        .flat_map(|t| read_dir_sorted(&t.join("log").join("cooker")))
        .flat_map(|m| read_dir_sorted(&m))
        .filter(|p| p.extension().is_some_and(|e| e == "log") && p.is_file())
        .collect();
    sort_newest_first(&mut logs);
    logs.into_iter().next()
}

fn read_dir_sorted(dir: &Path) -> Vec<PathBuf> {
    let mut v: Vec<PathBuf> = match fs::read_dir(dir) {
        Ok(rd) => rd.filter_map(|e| e.ok().map(|e| e.path())).collect(),
        Err(_) => Vec::new(),
    };
    v.sort();
    v
}

fn mtime(p: &Path) -> SystemTime {
    fs::metadata(p)
        .and_then(|m| m.modified())
        .unwrap_or(SystemTime::UNIX_EPOCH)
}

fn sort_newest_first(v: &mut [PathBuf]) {
    v.sort_by(|a, b| mtime(b).cmp(&mtime(a)).then_with(|| b.cmp(a)));
}

/// The value printed by `bitbake-getvar --value`: the last non-empty line of stdout
/// (setup scripts may print before it).
pub fn parse_getvar_value(stdout: &str) -> Option<String> {
    stdout
        .lines()
        .map(str::trim)
        .rfind(|l| !l.is_empty())
        .map(str::to_string)
}

/// `T` (the task log directory) of `recipe`, by running
/// `bitbake-getvar -r <recipe> --value T` in the build environment. This is the
/// authoritative path; [`find_task_logs`] is the fallback when there is no environment.
pub async fn t_dir_from_bitbake(env: &BbEnv, recipe: &str) -> Result<PathBuf> {
    check_name("recipe", recipe)?;
    let mut cmd = env.command("bitbake-getvar", &["-r", recipe, "--value", "T"])?;
    cmd.kill_on_drop(true);
    let out = tokio::time::timeout(GETVAR_TIMEOUT, cmd.output())
        .await
        .map_err(|_| Error::Invalid {
            msg: format!(
                "bitbake-getvar -r {recipe} T timed out after {}s",
                GETVAR_TIMEOUT.as_secs()
            ),
        })??;
    if !out.status.success() {
        let err = String::from_utf8_lossy(&out.stderr);
        return Err(Error::Invalid {
            msg: format!(
                "bitbake-getvar -r {recipe} T failed: {}",
                render::snippet(err.lines().last().unwrap_or("no output"))
            ),
        });
    }
    let value = parse_getvar_value(&String::from_utf8_lossy(&out.stdout));
    match value {
        Some(v) if v.starts_with('/') => Ok(PathBuf::from(v)),
        _ => Err(Error::Invalid {
            msg: format!("bitbake-getvar -r {recipe} T printed no absolute path"),
        }),
    }
}

/// The task's definition in the layers, through the index: the function named `task` in
/// the preferred recipe `recipe`, its bbappends, or the files they include and inherit.
///
/// A definition in the recipe or one of its bbappends is preferred to one in an included
/// file or a class (the class default is what the recipe overrides); within each group the
/// last one in parse order wins. The global classes (`base`, static `INHERIT` words) count
/// as included first, so `do_fetch` of a recipe that keeps it finds `base_do_fetch`. Static resolution only: `None` when the index has no such
/// recipe or no function of that name.
pub fn task_definition(index: &Index, ws: &Workspace, recipe: &str, task: &str) -> Option<Loc> {
    use crate::index::query;
    let row = query::preferred_recipe(index, recipe, None).ok()??;
    let mut own: Vec<i64> = vec![row.file.id];
    own.extend(
        query::appends_for(index, row.file.id)
            .ok()?
            .iter()
            .map(|f| f.id),
    );
    // Included and inherited files, with the name a class gives its default for the task
    // (`EXPORT_FUNCTIONS`: `<class>_<task>`).
    let mut pulled: Vec<(i64, Option<String>)> = Vec::new();
    // The global classes come first: BitBake inherits `base` and every `INHERIT` class
    // before it parses the recipe (`BBHandler`, "Configuration order" in
    // bitbake-semantics.md), and `base.bbclass` is where `do_fetch`, `do_unpack`,
    // `do_configure`, `do_compile`, `do_install` ... have their defaults (`base_do_<task>`,
    // `EXPORT_FUNCTIONS`). Without them a recipe that keeps the default task had no pointer.
    for class in global_classes(index) {
        let Ok(files) = query::class_files(index, ws, &class, true) else {
            continue;
        };
        if let Some(f) = files.into_iter().find(|c| c.rank.is_some()).map(|c| c.file)
            && !pulled.iter().any(|(id, _)| *id == f.id)
        {
            pulled.push((f.id, Some(format!("{class}_{task}"))));
        }
    }
    for root in &own {
        for node in query::tree(index, *root).ok()? {
            if let Some(f) = node.file
                && !own.contains(&f.id)
                && !pulled.iter().any(|(id, _)| *id == f.id)
            {
                let class_default = (f.kind == FileKind::Class)
                    .then(|| f.path.file_stem().and_then(|s| s.to_str()))
                    .flatten()
                    .map(|class| format!("{class}_{task}"));
                pulled.push((f.id, class_default));
            }
        }
    }
    let function = |file: i64, name: &str| -> Option<Loc> {
        query::statement_by_name(index, file, name)
            .ok()?
            .into_iter()
            .rfind(|s| s.kind == "function")
            .map(|s| s.loc)
    };
    own.iter()
        .rev()
        .find_map(|id| function(*id, task))
        .or_else(|| pulled.iter().rev().find_map(|(id, _)| function(*id, task)))
        .or_else(|| {
            pulled
                .iter()
                .rev()
                .find_map(|(id, class_default)| function(*id, class_default.as_deref()?))
        })
}

/// `base` and the words of every static `INHERIT` assignment in a `.conf` of the index
/// (words with `${` left out), without repeats, `base` first.
fn global_classes(index: &Index) -> Vec<String> {
    use crate::index::query;
    let mut out = vec!["base".to_string()];
    let scope = query::StatementFilter {
        kinds: vec!["assign".into()],
        ..query::StatementFilter::default()
    };
    for s in query::statements_by_base(index, "INHERIT", &scope).unwrap_or_default() {
        if s.flag.is_some() || s.loc.path.extension().is_none_or(|e| e != "conf") {
            continue;
        }
        for w in s.value.as_deref().unwrap_or("").split_whitespace() {
            if !w.contains("${") && !out.iter().any(|o| o == w) {
                out.push(w.to_string());
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn patterns_compile() {
        assert!(PATTERNS.is_some());
    }

    #[test]
    fn task_names() {
        assert_eq!(normalize_task("compile").unwrap(), "do_compile");
        assert_eq!(normalize_task("do_install").unwrap(), "do_install");
        assert!(normalize_task("../x").is_err());
        assert!(normalize_task("a/b").is_err());
        assert!(normalize_task("").is_err());
    }

    #[test]
    fn metadata_line_arithmetic() {
        let s = "x\n# line: 22, file: /l/a.bbclass\nf() {\n\tone\n\ttwo\n}\n";
        // Line 4 is the first body line: the definition line 22 plus one.
        assert_eq!(
            metadata_line(s, 4),
            Some((PathBuf::from("/l/a.bbclass"), 23))
        );
        assert_eq!(
            metadata_line(s, 5),
            Some((PathBuf::from("/l/a.bbclass"), 24))
        );
        assert_eq!(metadata_line(s, 1), None);
        assert_eq!(metadata_line(s, 99), None);
    }

    #[test]
    fn dedupes_repeated_errors() {
        let text = "ERROR: hello-1.0-r0 do_compile: QA Issue: x [ldflags]\n\
                    | ERROR: QA Issue: x [ldflags]\n";
        let f = detect(text);
        assert_eq!(f.len(), 1);
        assert_eq!(f[0].line, 1);
    }

    #[test]
    fn standard_traceback() {
        let text = "Traceback (most recent call last):\n  File \"/l/x.py\", line 3, in f\n    g()\nKeyError: 'A'\n";
        let f = detect(text);
        assert_eq!(f[0].kind, FailureKind::Python);
        assert_eq!(f[0].message, "KeyError: 'A'");
        assert_eq!(f[0].frames.len(), 1);
    }
}
